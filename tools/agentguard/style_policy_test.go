// styleOf 对单个文件跑 findStyleViolations，解析失败直接终止用例。
func styleOf(t *testing.T, name, src string, opts styleOptions) []string {
	t.Helper()
	got, err := findStyleViolations(name, []byte(src), opts)
	if err != nil {
		t.Fatalf("%s 解析失败：%v", name, err)
	}
	t.Logf("%s → %v", name, got)
	return got
}

// assertPrefixes 断言违规与 want 一一对应，且每条以对应前缀开头。
func assertPrefixes(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("期望 %d 条违规 %v，得到 %v", len(want), want, got)
	}
	for i, w := range want {
		if !strings.HasPrefix(got[i], w) {
			t.Fatalf("第 %d 条应以 %q 开头，得到 %q", i, w, got[i])
		}
	}
}

func TestFindStyleViolations_加锁后须紧跟同接收者defer解锁(t *testing.T) {
	src := `package p
import "sync"
type S struct{ mu sync.RWMutex; n int }
func (s *S) ok() { s.mu.Lock(); defer s.mu.Unlock(); s.n++ }
func (s *S) okR() int { s.mu.RLock(); defer s.mu.RUnlock(); return s.n }
func (s *S) bad() { s.mu.Lock(); s.n++; s.mu.Unlock() }
func (s *S) mismatch() { s.mu.RLock(); defer s.mu.Unlock() }
func (s *S) other(o *S) { s.mu.Lock(); defer o.mu.Unlock() }
func (s *S) inCase(x int) { switch x { case 1: s.mu.Lock(); s.n++ } }
func (s *S) last() { s.mu.Lock() }
func (s *S) closure() int { return func() int { s.mu.Lock(); defer s.mu.Unlock(); return s.n }() }
func (s *S) tryLock() { s.mu.TryLock() }
`
	got := styleOf(t, "p.go", src, styleOptions{})
	assertPrefixes(t, got, []string{
		"p.go:6: lock-defer：s.mu.Lock()",
		"p.go:7: lock-defer：s.mu.RLock()",
		"p.go:8: lock-defer：s.mu.Lock()",
		"p.go:9: lock-defer：s.mu.Lock()",
		"p.go:10: lock-defer：s.mu.Lock()",
	})
}

func TestFindStyleViolations_NewEvent只能在events包级var(t *testing.T) {
	const imp = "import \"github.com/japansms40-web/gohttpkit/logger\"\n"
	cases := []struct {
		name, file, src string
		want            []string
	}{
		{"events.go包级var放行", "pkg/events.go", "package pkg\n" + imp + "var evA = logger.NewEvent(\"a.b\")\n", nil},
		{"events.go函数体内拦", "pkg/events.go", "package pkg\n" + imp + "func f() { _ = logger.NewEvent(\"a.b\") }\n", []string{"pkg/events.go:3: event-decl："}},
		{"其它文件包级var拦", "pkg/a.go", "package pkg\n" + imp + "var evA = logger.NewEvent(\"a.b\")\n", []string{"pkg/a.go:3: event-decl："}},
		{"别名导入同样拦", "pkg/a.go", "package pkg\nimport lg \"github.com/japansms40-web/gohttpkit/logger\"\nvar evA = lg.NewEvent(\"a.b\")\n", []string{"pkg/a.go:3: event-decl："}},
		{"同名但不是kit的logger不管", "pkg/a.go", "package pkg\nimport \"example.com/logger\"\nvar evA = logger.NewEvent(\"a.b\")\n", nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			assertPrefixes(t, styleOf(t, c.file, c.src, styleOptions{}), c.want)
		})
	}
}

