func TestFindStyleViolations_panic只在Must与init与带指令函数(t *testing.T) {
	src := `package p
var err error
func MustGet() { panic(err) }
func mustOpen() { panic(err) }
func mustard() { panic(err) }
func init() { panic(err) }
func main() { panic(err) }
//agentguard:allow-panic 启动期注册，fail-fast 是契约
func Register() { panic(err) }
//agentguard:allow-panic
func NoReason() { panic(err) }
func Handle() { go func() { panic(err) }() }
var x = func() int { panic(err) }()
`
	got := styleOf(t, "p.go", src, styleOptions{})
	assertPrefixes(t, got, []string{
		"p.go:5: panic-placement",
		"p.go:7: panic-placement",
		"p.go:11: panic-placement",
		"p.go:12: panic-placement",
		"p.go:13: panic-placement",
	})
	mainPkg := "package main\nvar err error\nfunc main() { panic(err) }\n"
	if got := styleOf(t, "cmd/x/main.go", mainPkg, styleOptions{}); len(got) != 0 {
		t.Fatalf("package main 的 main 可以 panic，得到 %v", got)
	}
}

func TestFindStyleViolations_生产代码不硬造根ctx(t *testing.T) {
	src := "package p\nimport \"context\"\nfunc f() { _ = context.Background(); _ = context.TODO() }\n"
	assertPrefixes(t, styleOf(t, "pkg/p.go", src, styleOptions{}), []string{
		"pkg/p.go:3: root-ctx", "pkg/p.go:3: root-ctx",
	})
	alias := "package p\nimport stdctx \"context\"\nfunc f() { _ = stdctx.Background() }\n"
	assertPrefixes(t, styleOf(t, "pkg/p.go", alias, styleOptions{}), []string{"pkg/p.go:3: root-ctx"})
	if got := styleOf(t, "logger/p.go", src, styleOptions{rootCtxAllow: []string{"logger/"}}); len(got) != 0 {
		t.Fatalf("root_ctx_allow 前缀下放行，得到 %v", got)
	}
	mainPkg := "package main\nimport \"context\"\nfunc main() { _ = context.Background() }\n"
	if got := styleOf(t, "cmd/x/main.go", mainPkg, styleOptions{}); len(got) != 0 {
		t.Fatalf("package main 没有上游 ctx，放行，得到 %v", got)
	}
	derived := "package p\nimport \"context\"\nfunc f(ctx context.Context) { _ = context.WithoutCancel(ctx) }\n"
	if got := styleOf(t, "pkg/p.go", derived, styleOptions{}); len(got) != 0 {
		t.Fatalf("从上游 ctx 派生不算硬造，得到 %v", got)
	}
}

func TestFindStyleViolations_有方法的文件不放纯辅助函数(t *testing.T) {
	src := `package p
import "context"
type T struct{}
func (T) M() {}
func newT() T { return T{} }
func NewT() T { return T{} }
func doCall(ctx context.Context) {}
func init() {}
func _() {}
func helper() {}
func newline() {}
`
	on := styleOptions{helperPlacement: true}
	assertPrefixes(t, styleOf(t, "p.go", src, on), []string{
		"p.go:10: helper-placement：纯辅助函数 helper",
		"p.go:11: helper-placement：纯辅助函数 newline",
	})
	if got := styleOf(t, "p.go", src, styleOptions{}); len(got) != 0 {
		t.Fatalf("开关关闭时不检查，得到 %v", got)
	}
	if got := styleOf(t, "common.go", src, on); len(got) != 0 {
		t.Fatalf("common.go 自身不检查，得到 %v", got)
	}
	noMethod := "package p\nfunc helper() {}\n"
	if got := styleOf(t, "q.go", noMethod, on); len(got) != 0 {
		t.Fatalf("没有方法的文件不受约束，得到 %v", got)
	}
	exempt := styleOptions{helperPlacement: true, helperPlacementExempt: []string{"pkg/p.go"}}
	if got := styleOf(t, "pkg/p.go", src, exempt); len(got) != 0 {
		t.Fatalf("helper_placement_exempt 列出的文件放行，得到 %v", got)
	}
	if got := styleOf(t, "pkg/sub/p.go", src, exempt); len(got) != 2 {
		t.Fatalf("放行按完整路径匹配，不按前缀或文件名，得到 %v", got)
	}
}

func TestScanStyle_读HEAD配置开关(t *testing.T) {
	dir := t.TempDir()
	initRepo(t, dir, map[string]string{
		configPath: "style:\n  helper_placement: true\n",
		"pkg/a.go": "package pkg\ntype T struct{}\nfunc (T) M() {}\nfunc helper() {}\n",
	})
	if err := os.WriteFile(filepath.Join(dir, "pkg/b.go"), []byte("package pkg\nimport \"context\"\nvar c = context.TODO()\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := scanStyle(dir)
	t.Logf("violations=%v err=%v", got, err)
	if err != nil {
		t.Fatal(err)
	}
	assertPrefixes(t, got, []string{"pkg/a.go:4: helper-placement", "pkg/b.go:3: root-ctx"})
}

